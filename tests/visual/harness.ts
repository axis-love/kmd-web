/**
 * Visual baseline test harness — loads pre-rendered HTML fixtures
 * for Playwright screenshot comparison.
 *
 * The fixtures are pre-rendered by `tests/visual/prerender.ts` (run via
 * `npx tsx tests/visual/prerender.ts` or `npm run build:visual`).
 * Pre-rendering is necessary because the built dist artifacts use
 * extensionless internal imports (a known contracts package issue)
 * that Node ESM cannot resolve. The pre-render script uses tsx which
 * handles this correctly.
 */

