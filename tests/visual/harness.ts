export type VisualFixtureName = keyof typeof VISUAL_FIXTURES;
export const FIXTURE_NAMES = Object.keys(VISUAL_FIXTURES) as VisualFixtureName[];

/**
 * Read a pre-rendered fixture HTML file.
 * The file must be generated by `npx tsx tests/visual/prerender.ts`.
 */
export function readFixtureHtml(
  fixtureName: VisualFixtureName,
  theme: "light" | "dark",
  viewport: "desktop" | "narrow",
): string {
  const repoRoot = process.cwd();
  const filename = `${fixtureName}-${theme}-${viewport}.html`;
  return readFileSync(join(repoRoot, "tests", "visual", "fixtures", filename), "utf-8");
}
